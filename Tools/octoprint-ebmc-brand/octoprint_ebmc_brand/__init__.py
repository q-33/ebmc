"""EBMC Brand: shows the East Bay Makers Club badge in place of OctoPrint's logos and gives
OctoPrint's web interface the club's colours (after eastbaymakersclub.com).

Looks only: no printer commands, no API, no settings. The name "OctoPrint" and its credits
stay as they are; no sizes or spacing change.

  * main page: stylesheets (ebmc_palette.css: the club colours as CSS variables, generated;
    ebmc_brand.css: navbar mark, graph background, first-run wizard image and the colours)
    and a small script that points the page's icon links (favicon, apple-touch icons,
    pinned-tab icon, web app manifest) at this plugin's images;
  * login page: OctoPrint's "octoprint.theming.login" hook adds the palette and a login
    stylesheet (badge above the form, club colours). The login page loads no plugin
    scripts, so its browser-tab icon stays OctoPrint's.

The images and ebmc_palette.css are generated by Tools/EBMC/generate_octoprint_brand.py.
"""

import flask

import octoprint.plugin


class EbmcBrandPlugin(octoprint.plugin.AssetPlugin):
    def get_assets(self):
        return {
            "js": ["js/ebmc_brand.js"],
            "css": ["css/ebmc_palette.css", "css/ebmc_brand.css"],
        }

    def login_theming(self):
        # Plugin asset blueprints are registered under "plugin.<identifier>".
        endpoint = f"plugin.{self._identifier}.static"
        return [
            flask.url_for(endpoint, filename="css/ebmc_palette.css"),
            flask.url_for(endpoint, filename="css/ebmc_brand_login.css"),
        ]


__plugin_name__ = "EBMC Brand"
__plugin_version__ = "1.2.0"
__plugin_description__ = (
    "Shows the East Bay Makers Club badge in place of OctoPrint's logos and uses the club's colours."
)
__plugin_pythoncompat__ = ">=3.7,<4"


def __plugin_load__():
    global __plugin_implementation__
    global __plugin_hooks__
    __plugin_implementation__ = EbmcBrandPlugin()
    __plugin_hooks__ = {"octoprint.theming.login": __plugin_implementation__.login_theming}
